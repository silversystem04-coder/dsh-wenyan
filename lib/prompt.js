/**
 * 文言模式真正干活的地方：一段注入到系统提示里的规约。
 *
 * 为什么是「注入提示」而不是「把界面文字转写一遍」：
 * 文言不是词表替换能做的事（「的」→「之」只会得到半文半白的怪物）。
 * 要让回答和思考链真是文言，只能由模型自己写 —— 我们能做的是把规矩说死，
 * 并且明确哪些东西**不许**动（代码、路径、报错原文、数字）。
 *
 * 也因此天然满足「只换新的」：提示在每回合装配时读取，改了就只影响之后的生成，
 * 已经印在屏幕上的句子一个字都不会被回改。
 */

