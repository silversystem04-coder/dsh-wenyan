const GLOSS_RULE = '八、每段末附白话一句，冠以「白话：」，供速览；代码块之后不必附。';

/**
 * 生成注入文本。关着的时候返回空串 —— 上层据此判断「这一回合要不要注入」。
 * 返回空串而不是 null，是因为 systemPrompt.context 的 text() 只认字符串。
 */
export function promptText(state) {
  if (!state || state.on !== true) return '';
  const style = styleOf(state.style);
  const lines = [
    PREAMBLE,
    '',
    `风格：${style.label} —— ${style.rules}`,
    `示例：${style.sample}`,
  ];
  if (state.gloss === true) lines.push('', GLOSS_RULE);
  return lines.join('\n');
}

/** 一句话状态，给 ping / 工具输出用。 */
export function describe(state) {
  if (!state || state.on !== true) return '文言模式：关';
  const style = styleOf(state.style);
  return `文言模式：开 · ${style.label}${state.gloss ? ' · 附白话' : ''}`;
}
